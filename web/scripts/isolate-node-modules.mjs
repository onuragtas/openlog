// Some npm packages ship .go files (e.g. flatted). Without a go.mod boundary,
// `go build ./...` / `go vet ./...` at the repo root would treat them as
// packages of github.com/onuragtas/openlog/web/node_modules/... . A go.mod in
// node_modules makes it a separate module, which `./...` patterns skip.
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "node_modules");
if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, "go.mod"), "// Generated by web/scripts/isolate-node-modules.mjs\nmodule ignore/node_modules\n");
