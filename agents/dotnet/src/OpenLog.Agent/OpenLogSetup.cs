/// <summary>
/// Runtime-level propagator (HttpClient's DiagnosticsHandler, ASP.NET Core hosting): W3C tracecontext keeping the
/// random flag, plus baggage. The OpenTelemetry instrumentations also inject/extract with the SDK propagator.
/// </summary>
internal sealed class OpenLogDistributedContextPropagator : DistributedContextPropagator
{
    private static readonly DistributedContextPropagator Inner = CreateDefaultPropagator();

    public override IReadOnlyCollection<string> Fields => Inner.Fields;

    public override void Inject(Activity? activity, object? carrier, PropagatorSetterCallback? setter)
    {
        if (activity == null || setter == null || activity.IdFormat != ActivityIdFormat.W3C)
        {
            Inner.Inject(activity, carrier, setter);
            return;
        }
        var flags = (int)activity.ActivityTraceFlags & 0x03;
        setter(carrier, OpenLogTraceContextPropagator.TraceParent,
            "00-" + activity.TraceId.ToHexString() + "-" + activity.SpanId.ToHexString() + "-" + flags.ToString("x2", System.Globalization.CultureInfo.InvariantCulture));
        if (!string.IsNullOrEmpty(activity.TraceStateString)) setter(carrier, OpenLogTraceContextPropagator.TraceState, activity.TraceStateString);
        // baggage
        var baggage = activity.Baggage.ToList();
        if (baggage.Count > 0)
        {
            setter(carrier, "baggage", string.Join(",", baggage.Select(kv => Uri.EscapeDataString(kv.Key) + "=" + Uri.EscapeDataString(kv.Value ?? ""))));
        }
    }

    public override void ExtractTraceIdAndState(object? carrier, PropagatorGetterCallback? getter, out string? traceId, out string? traceState)
    {
        Inner.ExtractTraceIdAndState(carrier, getter, out traceId, out traceState);
    }

    public override IEnumerable<KeyValuePair<string, string?>>? ExtractBaggage(object? carrier, PropagatorGetterCallback? getter)
    {
        return Inner.ExtractBaggage(carrier, getter);
    }
}
#endif
