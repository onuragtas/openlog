// A country's name in the reader's language.
//
// The web asks the browser (Intl.DisplayNames). Dart has nothing of the kind:
// neither intl nor Flutter carries territory names, and a package for one
// table is a dependency too many. So this is the same table, the browser's own
// CLDR names, written out once by running Intl.DisplayNames over every
// two-letter code for the two languages this app speaks. A code it does not
// know stays a code, as on the web.

/// [code]'s name in [language], or [code] itself when it is not a known one.
String countryName(String code, String language) {
  final names = language == 'tr' ? _tr : _en;
  return names[code.toUpperCase()] ?? code;
}

